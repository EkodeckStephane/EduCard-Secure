function normalizePhrase(value: string): string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
}
for (const phrase of phrases) {
  phraseIndex.set(phrase.fr, phrase);
  phraseIndex.set(phrase.en, phrase);
  normalizedPhraseIndex.set(normalizePhrase(phrase.fr), phrase);
  normalizedPhraseIndex.set(normalizePhrase(phrase.en), phrase);
}
for (const [alias, canonical] of Object.entries(aliases)) {
  const phrase = phraseIndex.get(canonical);
  if (phrase) {
    phraseIndex.set(alias, phrase);
    normalizedPhraseIndex.set(normalizePhrase(alias), phrase);
  }
}

